import test from 'node:test';
import assert from 'node:assert/strict';
import pg from 'pg';
import { buildApp } from '../src/app.mjs';

const enabled=Boolean(process.env.DATABASE_URL&&process.env.BOOTSTRAP_ADMIN_USERNAME&&process.env.BOOTSTRAP_ADMIN_PASSWORD);
test('PostgreSQL inventory cycle count: snapshot, blind count, new lot, approval, movements, balanced GL and duplicate prevention',{skip:!enabled},async()=>{
 const pool=new pg.Pool({connectionString:process.env.DATABASE_URL});
 const app=buildApp({logger:false,db:pool,jwtSecret:process.env.AUTH_JWT_SECRET});
 const suffix=Date.now().toString(),code=p=>(p+suffix).slice(0,40),lot='COUNT-'+suffix;
 try{
  const login=await app.inject({method:'POST',url:'/api/v1/auth/login',payload:{username:process.env.BOOTSTRAP_ADMIN_USERNAME,password:process.env.BOOTSTRAP_ADMIN_PASSWORD}});
  assert.equal(login.statusCode,200,login.body);
  const headers={authorization:'Bearer '+login.json().accessToken,'content-type':'application/json'};
  const company=(await pool.query('INSERT INTO companies(code,name_ar) VALUES($1,$2) RETURNING id',[code('CNCO'),'شركة جرد اختبار'])).rows[0];
  const plant=(await pool.query('INSERT INTO plants(company_id,code,name_ar) VALUES($1,$2,$3) RETURNING id',[company.id,code('CNPL'),'مصنع جرد'])).rows[0];
  const warehouse=(await pool.query('INSERT INTO warehouses(plant_id,code,name_ar) VALUES($1,$2,$3) RETURNING id',[plant.id,code('CNWH'),'مخزن الجرد'])).rows[0];
  const unit=(await pool.query('INSERT INTO units_of_measure(code,name_ar) VALUES($1,$2) RETURNING id',[code('CNKG'),'كيلوجرام'])).rows[0];
  const category=(await pool.query("INSERT INTO item_categories(code,name_ar,category_kind) VALUES($1,$2,'RAW_MATERIAL') RETURNING id",[code('CNCAT'),'خامات الجرد'])).rows[0];
  const item=(await pool.query('INSERT INTO items(code,name_ar,category_id,base_unit_id,tracks_lot) VALUES($1,$2,$3,$4,TRUE) RETURNING id',[code('CNITEM'),'خامة موجودة',category.id,unit.id])).rows[0];
  const newItem=(await pool.query('INSERT INTO items(code,name_ar,category_id,base_unit_id,tracks_lot) VALUES($1,$2,$3,$4,TRUE) RETURNING id',[code('CNNEW'),'خامة غير مسجلة بالرصيد',category.id,unit.id])).rows[0];
  await pool.query("INSERT INTO inventory_balances(warehouse_id,item_id,lot_no,quantity,average_unit_cost,quality_status) VALUES($1,$2,$3,10,5,'RELEASED')",[warehouse.id,item.id,lot]);
  const created=await app.inject({method:'POST',url:'/api/v1/inventory/counts',headers,payload:{countNo:code('COUNT'),warehouseId:warehouse.id,reason:'جرد دوري اختباري'}});
  assert.equal(created.statusCode,201,created.body);
  const countId=created.json().id;
  const snapshot=(await pool.query('SELECT id,expected_qty FROM inventory_count_lines WHERE count_id=$1 AND item_id=$2',[countId,item.id])).rows[0];
  assert.equal(Number(snapshot.expected_qty),10);
  const setExisting=await app.inject({method:'PUT',url:'/api/v1/inventory/counts/'+countId+'/lines/'+snapshot.id,headers,payload:{countedQty:8}});
  assert.equal(setExisting.statusCode,200,setExisting.body);
  const addMissing=await app.inject({method:'POST',url:'/api/v1/inventory/counts/'+countId+'/lines',headers,payload:{itemId:newItem.id,lotNo:'NEW-'+suffix,countedQty:3,unitCost:4}});
  assert.equal(addMissing.statusCode,201,addMissing.body);
  const submit=await app.inject({method:'POST',url:'/api/v1/inventory/counts/'+countId+'/submit',headers,payload:{}});
  assert.equal(submit.statusCode,200,submit.body);
  assert.equal(submit.json().status,'COUNTED');
  const approve=await app.inject({method:'POST',url:'/api/v1/inventory/counts/'+countId+'/approve',headers,payload:{}});
  assert.equal(approve.statusCode,200,approve.body);
  assert.equal(approve.json().status,'POSTED');
  assert.equal(approve.json().changedLines,2);
  assert.equal(Number(approve.json().inventoryGain),12);
  assert.equal(Number(approve.json().inventoryLoss),10);
  const balances=await pool.query('SELECT item_id,quantity,average_unit_cost,quality_status FROM inventory_balances WHERE warehouse_id=$1 AND item_id=ANY($2::uuid[]) ORDER BY item_id',[warehouse.id,[item.id,newItem.id]]);
  const byItem=new Map(balances.rows.map(x=>[x.item_id,x]));
  assert.equal(Number(byItem.get(item.id).quantity),8);
  assert.equal(Number(byItem.get(newItem.id).quantity),3);
  assert.equal(byItem.get(newItem.id).quality_status,'PENDING_QC');
  const movements=await pool.query("SELECT movement_type,quantity_in,quantity_out FROM stock_movements WHERE reference_type='INVENTORY_COUNT' AND reference_id=$1",[countId]);
  assert.equal(movements.rowCount,2);
  const journal=await pool.query("SELECT id,total_debit,total_credit FROM journal_entries WHERE source_type='INVENTORY_COUNT' AND source_id=$1 AND status='POSTED'",[countId]);
  assert.equal(journal.rowCount,1);
  assert.equal(Number(journal.rows[0].total_debit),2);
  assert.equal(Number(journal.rows[0].total_credit),2);
  const lines=await pool.query('SELECT COALESCE(SUM(debit),0) debit,COALESCE(SUM(credit),0) credit FROM journal_lines WHERE journal_entry_id=$1',[journal.rows[0].id]);
  assert.equal(Number(lines.rows[0].debit),Number(lines.rows[0].credit));
  const duplicate=await app.inject({method:'POST',url:'/api/v1/inventory/counts/'+countId+'/approve',headers,payload:{}});
  assert.equal(duplicate.statusCode,409,duplicate.body);
  const list=await app.inject({method:'GET',url:'/api/v1/inventory/counts',headers});
  assert.equal(list.statusCode,200,list.body);
  assert.ok(list.json().some(x=>x.id===countId&&x.lines.length===2));
 }finally{await app.close();await pool.end();}
});
